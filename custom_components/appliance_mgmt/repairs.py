"""Repair flows."""

from __future__ import annotations

from typing import Any

import voluptuous as vol

from homeassistant.components.repairs import RepairsFlow
from homeassistant.core import HomeAssistant
from homeassistant.data_entry_flow import FlowResult

from .migrate import ISSUE_OLD_FOLDER, OLD_DOMAIN, async_remove_old_folder


class OldFolderFlow(RepairsFlow):
    """Remove the Appliance Live Activity folder, then ask for a restart."""

    async def async_step_init(
        self, user_input: dict[str, Any] | None = None
    ) -> FlowResult:
        return await self.async_step_confirm()

    async def async_step_confirm(
        self, user_input: dict[str, Any] | None = None
    ) -> FlowResult:
        if user_input is not None:
            await async_remove_old_folder(self.hass)
            return self.async_create_entry(data={})
        return self.async_show_form(
            step_id="confirm",
            data_schema=vol.Schema({}),
            description_placeholders={"folder": f"custom_components/{OLD_DOMAIN}"},
        )


async def async_create_fix_flow(
    hass: HomeAssistant, issue_id: str, data: dict[str, Any] | None
) -> RepairsFlow:
    if issue_id == ISSUE_OLD_FOLDER:
        return OldFolderFlow()
    raise ValueError(issue_id)
